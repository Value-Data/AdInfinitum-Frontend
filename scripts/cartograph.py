#!/usr/bin/env python3
"""Cartógrafo del frontend de AdInfinitum. Solo stdlib. Sobrescribe STATE.md.

Indexa: rutas de App.tsx, componentes (por árbol: f6, legacy, pages, components, layouts),
hooks, contextos, servicios/endpoints, tipos generados vs. a mano, tests y deuda medible
(isAdmin, style={{}}, hex sueltos, .catch tragados). STATE.md se genera, no se edita.
"""
from __future__ import annotations

import datetime as _dt
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
TESTS = ROOT / "__tests__"


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8", errors="replace")


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                              encoding="utf-8", timeout=20).stdout.strip()
    except Exception:
        return "?"


SRC_FILES = sorted(p for p in SRC.rglob("*") if p.suffix in {".ts", ".tsx"})

# ---------- rutas ----------
ROUTE_RE = re.compile(r'path\s*=\s*"([^"]+)"\s*element=\{(?=([\s\S]{0,300}))')  # lookahead: no consume la ruta siguiente
WRAPPERS = {"Suspense", "ProtectedRoute", "LoadingSpinner"}
app = read(SRC / "App.tsx") if (SRC / "App.tsx").exists() else ""
routes = []
for path, el in ROUTE_RE.findall(app):
    el = el.split("<Route")[0]  # solo el elemento de esta ruta
    tags = [t for t in re.findall(r"<(\w+)", el) if t not in WRAPPERS]
    guard = " (requireAdmin)" if "requireAdmin" in el else ""
    routes.append((path, (tags[0] if tags else "?") + guard))

# ---------- componentes ----------
COMP_RE = re.compile(r"export\s+(?:default\s+)?function\s+([A-Z]\w*)|export\s+const\s+([A-Z]\w*)\s*[:=]")
TREES = {
    "src/f6": SRC / "f6",
    "src/legacy": SRC / "legacy",
    "src/pages": SRC / "pages",
    "src/components": SRC / "components",
    "src/layouts": SRC / "layouts",
    "src/context": SRC / "context",
    "src/i18n": SRC / "i18n",
}
components: dict[str, list[tuple[str, list[str], int]]] = {}
for tree, d in TREES.items():
    rows = []
    for f in sorted(d.rglob("*.tsx")) if d.exists() else []:
        txt = read(f)
        names = [a or b for a, b in COMP_RE.findall(txt)]
        rows.append((rel(f), names, txt.count("\n") + 1))
    components[tree] = rows
n_comp_files = sum(len(v) for v in components.values())

# ---------- hooks ----------
HOOK_RE = re.compile(r"export\s+(?:default\s+)?(?:function|const)\s+(use[A-Z]\w*)|export\s*\{\s*(use[A-Z]\w*)\s*\}\s*from")
hooks = [(rel(f), a or (b + " (re-export)")) for f in SRC_FILES for a, b in HOOK_RE.findall(read(f))]

# ---------- servicios / endpoints ----------
EP_RE = re.compile(r"\bapi\.(get|post|put|patch|delete)\s*(?:<[^>]*>)?\(\s*[`'\"]([^`'\"]+)")
services = {}
for f in [SRC / "services" / "api.ts", SRC / "services" / "apiV2.ts", SRC / "legacy" / "api.ts"]:
    if f.exists():
        services[rel(f)] = sorted(set((m.upper(), u) for m, u in EP_RE.findall(read(f))))
n_endpoints = sum(len(v) for v in services.values())

# ---------- contrato ----------
openapi_ops = 0
openapi_path = ROOT / "openapi.json"
if openapi_path.exists():
    try:
        spec = json.loads(read(openapi_path))
        openapi_ops = sum(1 for p in spec.get("paths", {}).values() for k in p
                          if k in {"get", "post", "put", "patch", "delete"})
        has_caps = "capabilit" in read(openapi_path)
    except Exception:
        has_caps = False
else:
    has_caps = False
generated = SRC / "types" / "api.d.ts"
gen_header = generated.exists() and "auto-generated by openapi-typescript" in read(generated)[:300]
handwritten_types = [rel(p) for p in sorted((SRC / "types").glob("*.ts")) if p.name != "api.d.ts"]

# ---------- tests ----------
test_files = sorted(p for p in TESTS.rglob("*") if re.search(r"\.test\.(ts|tsx)$", p.name)) if TESTS.exists() else []
test_by_dir: dict[str, int] = {}
for p in test_files:
    k = p.parent.relative_to(TESTS).as_posix().split("/")[0]
    test_by_dir[k] = test_by_dir.get(k, 0) + 1

# ---------- deuda medible ----------
def count(pattern: str, files=SRC_FILES) -> tuple[int, int]:
    rx = re.compile(pattern)
    total, nfiles = 0, 0
    for f in files:
        c = len(rx.findall(read(f)))
        total += c
        nfiles += 1 if c else 0
    return total, nfiles

debt = {
    "isAdmin": count(r"\bisAdmin\b"),
    "style={{": count(r"style=\{\{"),
    "hex sueltos (fuera de tokens.css)": count(r"#[0-9a-fA-F]{6}\b"),
    "error tragado .catch(() => setX([]|null))": count(r"\.catch\(\s*\(\)\s*=>\s*set\w*\(\s*(?:\[\]|null)\s*\)\s*\)"),
    "window.confirm": count(r"window\.confirm\("),
    "gauge": count(r"(?i)gauge"),
    ": any / as any": count(r":\s*any\b|as\s+any\b"),
}
big_files = sorted(((rel(f), read(f).count("\n") + 1) for f in SRC_FILES), key=lambda x: -x[1])[:8]

# ---------- salida ----------
now = _dt.datetime.now().strftime("%Y-%m-%d %H:%M")
head = git("rev-parse", "--short", "HEAD")
branch = git("rev-parse", "--abbrev-ref", "HEAD")
n_src = len(SRC_FILES)

out: list[str] = []
w = out.append
w("# STATE.md — AdInfinitum Frontend")
w("")
w("<!-- GENERADO por scripts/cartograph.py. No editar a mano: regenerar. -->")
w(f"Generado: {now} · rama `{branch}` @ `{head}`")
w("")
per_tree = ", ".join("%s %d" % (k.split("/")[-1], len(v)) for k, v in components.items())
w(f"**{len(routes)} rutas en App.tsx · {n_comp_files} archivos de componente "
  f"({per_tree}) · "
  f"{len(hooks)} hooks · {n_endpoints} llamadas a endpoints en {len(services)} servicios · "
  f"{openapi_ops} operaciones en openapi.json · {len(test_files)} archivos de test · {n_src} archivos .ts/.tsx en src**")
w("")
w("## Rutas (src/App.tsx)")
w("| Path | Elemento |")
w("|---|---|")
for p, e in routes:
    w(f"| `{p}` | `{e}` |")
w("")
w("## Componentes por árbol")
for tree, rows in components.items():
    w(f"### {tree} ({len(rows)})")
    w("| Archivo | Exporta | Líneas |")
    w("|---|---|---|")
    for f, names, n in rows:
        w(f"| `{f}` | {', '.join(names) or '—'} | {n} |")
    w("")
w("## Hooks")
for f, h in hooks:
    w(f"- `{h}` — `{f}`")
w("")
w("## Contrato y tipos")
w(f"- `openapi.json`: {openapi_ops} operaciones. `capabilities` presente: {'sí' if has_caps else 'NO (F7 backend Fase 2 pendiente)'}")
w(f"- `src/types/api.d.ts` generado por openapi-typescript: {'sí' if gen_header else 'NO / falta'} (DENY: no editar)")
w(f"- Tipos a mano: {', '.join(f'`{t}`' for t in handwritten_types) or 'ninguno'}")
w("")
w("## Endpoints usados por servicio")
for f, eps in services.items():
    w(f"### `{f}` ({len(eps)})")
    for m, u in eps:
        w(f"- {m} `{u}`")
    w("")
w("## Tests (__tests__/)")
for k, v in sorted(test_by_dir.items()):
    w(f"- `{k}/`: {v}")
w("")
w("## Deuda medible (total · archivos)")
w("| Patrón | Ocurrencias | Archivos |")
w("|---|---|---|")
for k, (t, nf) in debt.items():
    w(f"| `{k}` | {t} | {nf} |")
w("")
w("## Archivos más grandes")
for f, n in big_files:
    w(f"- `{f}` — {n} líneas")
w("")

(ROOT / "STATE.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
print(f"STATE.md: {len(routes)} rutas | {n_comp_files} componentes | {len(hooks)} hooks | "
      f"{n_endpoints} endpoints | {openapi_ops} ops openapi | {len(test_files)} tests")
